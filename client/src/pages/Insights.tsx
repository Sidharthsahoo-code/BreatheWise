import { useState } from "react"
import { ChartColumn, Info, Lightbulb } from "lucide-react"
import { useApp } from "@/context/AppContext"
import { useAirQualityData } from "@/hooks/useAirQuality"
import { EmptyState } from "@/components/common/EmptyState"
import { ErrorState } from "@/components/common/ErrorState"
import { DailySummaries } from "@/components/insights/DailySummaries"
import { HourlyBars } from "@/components/insights/HourlyBars"
import { PollutantComparison } from "@/components/insights/PollutantComparison"
import { TrendChart } from "@/components/insights/TrendChart"
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card"
import { Skeleton } from "@/components/ui/skeleton"
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs"
import type { AirQualityForecast, AqiStandard, CurrentAirQuality } from "@/types/airQuality"
import { formatLocationShort } from "@/utils/formatters"
import { buildInsights, summarizeDays } from "@/utils/insights"

const INSIGHTS_RANGE = { pastDays: 7, forecastDays: 5 }

const HISTORY_OPTIONS = [
  { value: "24", label: "24 hours" },
  { value: "72", label: "3 days" },
  { value: "168", label: "7 days" },
]

function InsightsSkeleton() {
  return (
    <div className="space-y-6" aria-busy="true" aria-label="Loading insights">
      <Skeleton className="h-40 w-full rounded-2xl" />
      <Skeleton className="h-80 w-full rounded-2xl" />
      <div className="grid gap-4 lg:grid-cols-2">
        <Skeleton className="h-80 rounded-2xl" />
        <Skeleton className="h-80 rounded-2xl" />
      </div>
      <Skeleton className="h-80 w-full rounded-2xl" />
    </div>
  )
}

interface BodyProps {
  current: CurrentAirQuality
  forecast: AirQualityForecast
  standard: AqiStandard
  historyHours: number
}

function InsightsBody({ current, forecast, standard, historyHours }: BodyProps) {
  const { hourly } = forecast
  const standardName = current.standards[standard].name

  const today = current.dataTime.slice(0, 10)
  const allDays = summarizeDays(hourly, standard, today)
  const insights = buildInsights(hourly, standard, standardName, allDays)

  // Daily cards follow the chosen history window, plus every forecast day
  const nowIndex = hourly.map((h) => h.isForecast).lastIndexOf(false)
  const startDate = hourly[Math.max(0, nowIndex - historyHours)]?.time.slice(0, 10) ?? today
  const days = allDays.filter((d) => d.date >= startDate)

  return (
    <div className="space-y-6">
      <p className="flex gap-2 rounded-lg bg-muted/60 p-3 text-xs leading-relaxed text-muted-foreground">
        <Info className="mt-0.5 size-3.5 shrink-0" />
        <span>
          <span className="font-medium text-foreground">Modelled, not measured.</span> {forecast.source.note} Solid lines
          and &ldquo;Model analysis&rdquo; mark recent past hours; dashed lines and &ldquo;Forecast&rdquo; mark hours still to
          come.
        </span>
      </p>

      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2 text-lg">
            <Lightbulb className="size-5 text-primary" />
            Environmental insights
          </CardTitle>
        </CardHeader>
        <CardContent>
          {insights.length > 0 ? (
            <ul className="space-y-2.5 text-sm leading-relaxed">
              {insights.map((line, i) => (
                <li key={i} className="flex gap-2.5">
                  <span className="mt-2 size-1.5 shrink-0 rounded-full bg-primary" />
                  <span>{line}</span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-sm text-muted-foreground">Not enough data yet to calculate insights for this location.</p>
          )}
          <p className="mt-4 border-t pt-3 text-xs text-muted-foreground">
            Calculated directly from the model values shown below, not generated by AI.
          </p>
        </CardContent>
      </Card>

      <TrendChart
        title={`${standardName} trend`}
        description="Hourly values. The shaded bands mark the AQI categories."
        hourly={hourly}
        metric="aqi"
        standard={standard}
        unit={standardName}
        historyHours={historyHours}
        showBands
      />

      <div className="grid gap-4 lg:grid-cols-2">
        <TrendChart
          title="PM2.5"
          description="Fine particles, in µg/m³"
          hourly={hourly}
          metric="pm2_5"
          standard={standard}
          unit="µg/m³"
          historyHours={historyHours}
          guideline={{ value: 15, label: "WHO 24-hour guideline (15)" }}
        />
        <TrendChart
          title="PM10"
          description="Coarser particles, in µg/m³"
          hourly={hourly}
          metric="pm10"
          standard={standard}
          unit="µg/m³"
          historyHours={historyHours}
          guideline={{ value: 45, label: "WHO 24-hour guideline (45)" }}
        />
      </div>

      <HourlyBars hourly={hourly} standard={standard} unit={standardName} />

      <PollutantComparison pollutants={current.pollutants} />

      <DailySummaries days={days} standard={standard} standardName={standardName} />
    </div>
  )
}

export default function Insights() {
  const { location, aqiStandard, setAqiStandard } = useApp()
  const { current, forecast, loading, error, retry } = useAirQualityData(location, INSIGHTS_RANGE)
  const [historyHours, setHistoryHours] = useState(72)

  let content
  if (error) {
    content = <ErrorState message={error.message} onRetry={retry} />
  } else if (loading || !current || !forecast) {
    content = <InsightsSkeleton />
  } else if (!forecast.dataAvailable) {
    content = (
      <EmptyState
        icon={ChartColumn}
        title="No data for this location"
        description="The model has no air quality data here. Choose a nearby city from the location menu."
      />
    )
  } else {
    content = <InsightsBody current={current} forecast={forecast} standard={aqiStandard} historyHours={historyHours} />
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-4 lg:flex-row lg:items-end lg:justify-between">
        <div>
          <h1 className="text-2xl font-bold tracking-tight sm:text-3xl">Insights</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            Trends, forecasts and daily summaries for {formatLocationShort(location)}.
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-3">
          <Tabs value={String(historyHours)} onValueChange={(v) => setHistoryHours(Number(v))}>
            <TabsList aria-label="History range">
              {HISTORY_OPTIONS.map((o) => (
                <TabsTrigger key={o.value} value={o.value}>
                  {o.label}
                </TabsTrigger>
              ))}
            </TabsList>
          </Tabs>
          <Tabs value={aqiStandard} onValueChange={(v) => setAqiStandard(v as AqiStandard)}>
            <TabsList aria-label="AQI standard">
              <TabsTrigger value="us">US AQI</TabsTrigger>
              <TabsTrigger value="european">European AQI</TabsTrigger>
            </TabsList>
          </Tabs>
        </div>
      </div>

      {content}
    </div>
  )
}